// Compound assignment operators

let x = 10;
x += 5; // Equivalent to x = x + 5
console.log(x); // Outputs: 15  


x -= 3;
console.log(x); 


x *= 3; // Equivalent to x = x * 3
console.log(x); // Outputs: 36

x /= 3; // Equivalent to x = x / 3
console.log(x); // Outputs: 12

x %=2 // Equivalent to x = x % 2
console.log(x); // Outputs: 0   