//1. Logical AND (&&)
let a = true;
let b = false;
let c = a && b; // false
console.log("Logical AND (true && false):", c); // Outputs: false

//2. Logical OR (||)
let d = a || b; // true
console.log("Logical OR (true || false):", d); // Outputs: true

//3. Logical NOT (!)
let e = !a; // false
console.log("Logical NOT (!true):", e); // Outputs: false

