//1. Simple Assignment (=)
let x = 10; // Assigns the value 10 to variable x
console.log("Simple Assignment (x = 10):", x); 

//2. Addition Assignment (+=)
let y = 5; // Initial value of y
y += 3; // Equivalent to y = y + 3
console.log("Addition Assignment (y += 3):", y); // Outputs: 8

//3. Subtraction Assignment (-=)
let z = 15; // Initial value of z
z -= 4; // Equivalent to z = z - 4
console.log("Subtraction Assignment (z -= 4):", z); // Outputs: 11

//4. Multiplication Assignment (*=)
let a = 6; // Initial value of a
a *= 2; // Equivalent to a = a * 2
console.log("Multiplication Assignment (a *= 2):", a); // Outputs: 12       

//5. Division Assignment (/=)

let b = 20; // Initial value of b
b /= 4; // Equivalent to b = b / 4
console.log("Division Assignment (b /= 4):", b); // Outputs : 5

//6. Modulus Assignment (%=)
let c = 10; // Initial value of c
c %= 3; // Equivalent to c = c % 3
console.log("Modulus Assignment (c %= 3):", c); // Outputs: 1
      
//7. Exponentiation Assignment (**=)
let d = 2; // Initial value of d                        
d **= 3; // Equivalent to d = d ** 3
console.log("Exponentiation Assignment (d **= 3):", d); // Outputs: 8
