//1. Basic Operators
let a = 10;
let b = 5;
let sum = a + b; // Addition
let diff = a - b; // Subtraction
let product = a * b; // Multiplication
let quotient = a / b; // Division
let remainder = a % b; // Modulus
let power = a ** b; // Exponentiation

console.log("Addition:", sum);
console.log("Subtraction:", diff);
console.log("Multiplication:", product);
console.log("Division:", quotient);
console.log("Modulus:", remainder);
console.log("Exponentiation:", power);

//2. Advanced & Shortcut Operators
let i = 10;
i++; // Equivalent to i = i + 1
console.log("Increment (i++):", i); // Outputs: 11

i--; // Equivalent to i = i - 1
console.log("Decrement (i--):", i); // Outputs: 10

i = 10 % 3; // 1 (because 3 * 3 = 9, with 1 left over)
console.log(i);

let powerOfTwo = 2 ** 3; // 8 (2 * 2 * 2)
console.log("Exponentiation (2 ** 3):", powerOfTwo);

