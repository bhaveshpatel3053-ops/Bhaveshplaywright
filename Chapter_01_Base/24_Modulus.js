//1. Modulus Operator (%)
let num1 = 10;
let num2 = 3;
let modulusResult = num1 % num2;    
console.log(modulusResult);

//2. Modulus Assignment Operator (%=)
let num3 = 10;
num3 %= 3; 
console.log(num3); // Outputs: 1

let resesult = 10 % 3; // 1 (because 3 * 3 = 9, with 1 left over)
console.log(resesult);

